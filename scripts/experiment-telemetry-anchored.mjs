import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { autoPlacePcbWithReportAsync, renderPlacementSvg, renderPlacementSubsetSvg } from '../src/pcb-layout/pcb-auto-place/auto-place.ts';
import { createBoardAssemble } from '../src/pcb-layout/board-assemble.ts';
import { placementMetrics } from './experiment-placement-metrics.mjs';
import { terminatePcbSubtreeWorkerPool } from '../src/pcb-layout/pcb-auto-place-v2/tree-subtree-pool.ts';
const tag = process.argv[2] ?? 'after';
const dir = 'docs/experimental/pcb/telemetry-anchored-2026-09-27';
mkdirSync(dir, {recursive:true});
const input = JSON.parse(readFileSync('docs/experimental/pcb/global-placement-2026-09-27/Telemetry/input.json'));
process.env.PCB_BOARD_PACKER_PROFILE = '1';
const start = performance.now();
const result = await autoPlacePcbWithReportAsync(input, {logProgress:true});
const usb = new Set(['J5','R30','R31','F1','C41']);
writeFileSync(`${dir}/${tag}-board.svg`, renderPlacementSvg(input,result.placements));
writeFileSync(`${dir}/${tag}-usb.svg`, renderPlacementSubsetSvg(input,result.placements.filter(p=>usb.has(p.designator)), {padding:3,includeIgnoredSignals:true,ratsnestTopology:'mst'}));
writeFileSync(`${dir}/${tag}.json`,JSON.stringify({...result,ms:performance.now()-start,metrics:placementMetrics(input,result.placements)},null,2));
const fixed = new Set(input.components.filter(c=>c.pcb.fixedPlacement).map(c=>c.designator));
writeFileSync(`${dir}/${tag}.assemble.json`, JSON.stringify(createBoardAssemble(result.layout,{preserveBoard:true,preservedComponents:fixed}),null,2));
console.log(JSON.stringify({tag,ok:result.report.ok,ms:performance.now()-start,metrics:placementMetrics(input,result.placements)}));
await terminatePcbSubtreeWorkerPool();
